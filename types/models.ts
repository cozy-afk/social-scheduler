export type UserRole = 'admin' | 'va';

export type Platform = 'instagram' | 'tiktok' | 'x' | 'threads';

export type PostType =
  | 'instagram_post'
  | 'instagram_reel'
  | 'instagram_story'
  | 'tiktok_reel'
  | 'tiktok_slideshow'
  | 'tiktok_story'
  | 'x_post'
  | 'threads_post';

export type PostStatus = 'draft' | 'scheduled' | 'completed' | 'missing';

export type CaptionCategory =
  | 'ig_reels'
  | 'ig_post'
  | 'tiktok_slideshow'
  | 'tiktok_reel'
  | 'threads_post'
  | 'x_post'
  | 'general';

export interface PostingFrequencyConfig {
  platform: Platform;
  enabled: boolean;
  postsPerDay: number;          // 1–10
  startHour: number;            // 0–23
  endHour: number;              // 0–23
  postTypes: PostType[];        // cycling order
}

export interface MetaConnection {
  instagramAccountId?: string;
  accessToken?: string;
  connectedAt?: string;
  pageId?: string;
}

export interface Model {
  id: string;
  name: string;
  profileImage?: string;
  exifPreset: {
    device: string;
    model: string;
    lens: string;
    software: string;
    gpsLatitude: number;
    gpsLongitude: number;
    isoVariance: number[];
    focalLengthVariance: number[];
  };
  postingSchedule: TimeSlot[];
  postingFrequency: PostingFrequencyConfig[];
  assignedVaIds: string[];      // which VA user IDs can access this model
  status: 'active' | 'paused';
  createdAt: string;
  metaConnection?: MetaConnection;
}

export interface TimeSlot {
  id: string;
  time: string;
  platform: Platform;
  postType: PostType;
  recurrence: 'daily' | 'weekdays' | 'weekends';
}

export interface User {
  id: string;
  email: string;
  name: string;
  role: UserRole;
  assignedModels: string[];
}

export interface Asset {
  id: string;
  postId: string;
  fileUrl: string;
  fileName: string;
  fileType: 'image' | 'video';
  order: number;
  overlayConfig?: {
    text: string;
    position: { x: number; y: number };
    fontSize: number;
    fontFamily: string;
    color: string;
  };
  originalDimensions?: { width: number; height: number };
  cropConfig?: {
    strategy: 'center' | 'top' | 'bottom' | 'random' | 'face-detect' | 'rule-of-thirds';
    position?: { x: number; y: number; width: number; height: number };
  };
}

export interface Post {
  id: string;
  modelId: string;
  platform: Platform;
  postType: PostType;
  scheduledTime: string;
  status: PostStatus;
  description: string;     // Text that goes WITH the post
  imageCaption?: string;   // Text overlay directly ON the image(s)
  assets: Asset[];
  assignedVaId?: string;
  completedAt?: string;
  completedBy?: string;
  createdAt: string;
  updatedAt: string;
  isAutoGenerated?: boolean;
  approvalStatus?: 'pending' | 'approved' | 'rejected';
  approvedBy?: string;
  storyCategory?: 'daily-life' | 'food' | 'selfie' | 'gym' | 'other';
}

export interface Caption {
  id: string;
  category: CaptionCategory;
  platform: Platform;
  postType: PostType;
  text: string;
  performanceRating?: 'high' | 'medium' | 'low';
  tags: string[];
  modelId?: string;
  createdAt: string;
}

export interface GalleryAsset {
  id: string;
  fileName: string;
  fileUrl: string;
  thumbnailUrl?: string;
  fileType: 'image' | 'video';
  width?: number;
  height?: number;
  aspectRatio?: number;
  sizeBytes?: number;
  uploadedAt: string;
  source: 's3' | 'local';
  s3Key?: string;
}

export interface VAMagicLink {
  id: string;
  token: string;
  vaId: string;
  vaName: string;
  assignedModels: string[];
  createdAt: string;
  expiresAt: string;
  isActive: boolean;
  lastAccessedAt?: string;
}

export interface CalendarDay {
  date: string;
  posts: Post[];
}

export interface PostRequirement {
  timeSlot: string;
  platform: Platform;
  postType: PostType;
  status: PostStatus;
  post?: Post;
}
