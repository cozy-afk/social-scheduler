'use client';

import { useStore } from '@/lib/store';
import { useMemo, useState } from 'react';
import { format } from 'date-fns';
import { CheckCircle, XCircle, RefreshCw, Image as ImageIcon } from 'lucide-react';

export default function StoryApprovalQueue() {
  const { models, selectedModelId, posts, updatePost } = useStore();
  const [isGenerating, setIsGenerating] = useState(false);

  const selectedModel = models.find((m) => m.id === selectedModelId);

  const pendingStories = useMemo(() => {
    if (!selectedModel) return [];
    return posts
      .filter(
        (p) =>
          p.modelId === selectedModel.id &&
          p.isAutoGenerated === true &&
          p.approvalStatus === 'pending' &&
          (p.postType === 'instagram_story' || p.postType === 'tiktok_story')
      )
      .sort((a, b) => new Date(a.scheduledTime).getTime() - new Date(b.scheduledTime).getTime());
  }, [selectedModel, posts]);

  const handleApprove = (postId: string) => {
    updatePost(postId, { approvalStatus: 'approved', status: 'scheduled' });
  };

  const handleReject = (postId: string) => {
    updatePost(postId, { approvalStatus: 'rejected', status: 'draft' });
  };

  const handleGenerateStories = async () => {
    if (!selectedModel) return;
    setIsGenerating(true);
    try {
      const response = await fetch('/api/generate-stories', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          modelId: selectedModel.id,
          date: new Date().toISOString(),
          storiesPerDay: 4,
        }),
      });
      const data = await response.json();
      if (data.success) {
        alert(`Generated ${data.count} stories!`);
      }
    } catch {
      alert('Failed to generate stories');
    } finally {
      setIsGenerating(false);
    }
  };

  if (!selectedModel) {
    return (
      <div className="flex items-center justify-center h-64 text-slate-500">
        <p>Please select a model to view story approvals</p>
      </div>
    );
  }

  const getCategoryEmoji = (category?: string) => {
    switch (category) {
      case 'daily-life': return '🏠';
      case 'food': return '🍕';
      case 'selfie': return '🤳';
      case 'gym': return '💪';
      default: return '📸';
    }
  };

  return (
    <div className="space-y-5">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div>
          <h2 className="text-xl font-bold text-white">Story Approval Queue</h2>
          <p className="text-sm text-slate-400 mt-1">
            Review auto-generated stories before they go live
          </p>
        </div>
        <button
          onClick={handleGenerateStories}
          disabled={isGenerating}
          className="flex items-center gap-2 bg-violet-600 hover:bg-violet-500 disabled:opacity-50 text-white px-4 py-2 rounded-lg transition-all duration-150 self-start sm:self-auto text-sm font-medium"
        >
          <RefreshCw className={`w-4 h-4 ${isGenerating ? 'animate-spin' : ''}`} />
          {isGenerating ? 'Generating...' : 'Generate Stories'}
        </button>
      </div>

      {pendingStories.length === 0 ? (
        <div className="card flex flex-col items-center justify-center py-16 text-center">
          <ImageIcon className="w-12 h-12 text-slate-600 mx-auto mb-3" />
          <p className="text-slate-300 font-medium">No pending stories</p>
          <p className="text-slate-500 text-sm mt-1">
            Click &quot;Generate Stories&quot; to create auto-cropped stories from your vault
          </p>
        </div>
      ) : (
        <>
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
            {pendingStories.map((story) => {
              const asset = story.assets[0];
              const cropConfig = asset.cropConfig;

              return (
                <div
                  key={story.id}
                  className="card overflow-hidden border-yellow-500/30"
                >
                  {/* Story Preview */}
                  <div className="relative bg-slate-800 aspect-[9/16]">
                    <div className="absolute inset-0 flex items-center justify-center">
                      <div className="text-center p-4">
                        <ImageIcon className="w-10 h-10 mx-auto mb-2 text-slate-600" />
                        <p className="text-slate-400 text-sm">Story Preview</p>
                        <p className="text-slate-500 text-xs mt-1">
                          Crop: {cropConfig?.strategy || 'center'}
                        </p>
                        {cropConfig?.position && (
                          <p className="text-slate-600 text-xs mt-1 font-mono">
                            {cropConfig.position.width}×{cropConfig.position.height}
                          </p>
                        )}
                      </div>
                    </div>
                    {/* Category badge */}
                    <div className="absolute top-3 right-3 text-lg">
                      {getCategoryEmoji(story.storyCategory)}
                    </div>
                  </div>

                  {/* Story Info */}
                  <div className="p-4">
                    <div className="flex items-center justify-between mb-2">
                      <span className="text-sm font-semibold text-white">
                        {story.postType === 'instagram_story' ? '📸 Instagram' : '🎵 TikTok'} Story
                      </span>
                      <span className="text-xs text-slate-400 capitalize">
                        {story.storyCategory?.replace('-', ' ')}
                      </span>
                    </div>

                    <p className="text-xs text-slate-500 mb-3">
                      {format(new Date(story.scheduledTime), 'MMM d, h:mm a')}
                    </p>

                    {asset.originalDimensions && (
                      <div className="card-surface px-3 py-2 mb-3 text-xs space-y-1">
                        <div className="flex justify-between text-slate-400">
                          <span>Original</span>
                          <span className="font-mono">{asset.originalDimensions.width}×{asset.originalDimensions.height}</span>
                        </div>
                        <div className="flex justify-between text-slate-400">
                          <span>Strategy</span>
                          <span className="capitalize">{cropConfig?.strategy}</span>
                        </div>
                      </div>
                    )}

                    <div className="flex gap-2">
                      <button
                        onClick={() => handleReject(story.id)}
                        className="flex-1 flex items-center justify-center gap-1.5 bg-red-500/20 text-red-400 border border-red-500/30 px-3 py-2 rounded-lg hover:bg-red-500/30 transition-colors text-sm font-medium"
                      >
                        <XCircle className="w-4 h-4" />
                        Reject
                      </button>
                      <button
                        onClick={() => handleApprove(story.id)}
                        className="flex-1 flex items-center justify-center gap-1.5 bg-green-600 hover:bg-green-500 text-white px-3 py-2 rounded-lg transition-colors text-sm font-medium"
                      >
                        <CheckCircle className="w-4 h-4" />
                        Approve
                      </button>
                    </div>
                  </div>
                </div>
              );
            })}
          </div>

          <div className="bg-blue-500/10 border border-blue-500/30 rounded-xl p-4">
            <p className="text-sm text-blue-300">
              <span className="font-semibold">{pendingStories.length}</span> stor{pendingStories.length !== 1 ? 'ies' : 'y'} pending approval
            </p>
          </div>
        </>
      )}
    </div>
  );
}
